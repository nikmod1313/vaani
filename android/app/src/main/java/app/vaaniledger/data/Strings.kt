/**
 * User-facing text, in the two languages [AppLanguage] offers.
 *
 * ONE RULE DECIDES WHAT "HI" MEANS HERE: Hindi in Devanagari. Choosing हिंदी
 * gets the whole app in Devanagari, with the shop words people actually use
 * kept as they say them (एंट्री, ऑर्डर, UPI, WhatsApp). "EN" is full
 * English. Mixing scripts within one language reads as broken to whichever
 * audience did not ask for it.
 *
 * Covers the screens a shopkeeper actually lives in day to day: onboarding,
 * the setup screen, the bubble panel, and the review queue -- plus every
 * toast on the capture and import paths, since a shopkeeper who cannot tell
 * why a scan failed cannot fix it -- and, in [Sheets], the confirm, edit and
 * khata sheets over WhatsApp and the voice entry, which used to be
 * Hinglish-only whatever language had been chosen.
 */
